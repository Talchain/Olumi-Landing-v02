// Deploy only this isolated marketing directory. Never print the private claim link.
const fs=require('node:fs');
const path=require('node:path');
const crypto=require('node:crypto');
const {spawnSync}=require('node:child_process');
const assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const out=path.join(root,'evidence');
fs.mkdirSync(out,{recursive:true});
const tools=process.env.OLUMI_TOOLS;
const cli=path.join(tools,'node_modules/.bin/netlify');
const {chromium}=require(path.join(tools,'node_modules/playwright'));
const version=spawnSync(cli,['--version'],{cwd:root,encoding:'utf8'}).stdout.trim();
const result=spawnSync(cli,['deploy','--allow-anonymous','--prod','--dir','site','--no-build','--json','--timeout','180'],{cwd:root,encoding:'utf8',timeout:240000,env:{...process.env,CI:'true',NETLIFY_TELEMETRY_DISABLED:'1'}});
const raw=JSON.stringify({status:result.status,error:result.error?.message,stdout:result.stdout,stderr:result.stderr,version,at:new Date().toISOString()});
const key=crypto.randomBytes(32),iv=crypto.randomBytes(12);
const cipher=crypto.createCipheriv('aes-256-gcm',key,iv);
const ciphertext=Buffer.concat([cipher.update(raw,'utf8'),cipher.final()]);
const wrapped=crypto.publicEncrypt({key:fs.readFileSync(path.join(root,'scripts/deploy-receipt.public.pem')),oaepHash:'sha256',padding:crypto.constants.RSA_PKCS1_OAEP_PADDING},key);
const receipt={key:wrapped.toString('base64'),iv:iv.toString('base64'),ciphertext:ciphertext.toString('base64'),tag:cipher.getAuthTag().toString('base64')};
fs.writeFileSync(path.join(out,'private-receipt.encrypted.json'),JSON.stringify(receipt));
console.log('DEPLOY_PRIVATE_RECEIPT='+JSON.stringify(receipt));
if(result.status!==0)throw new Error('Deployment did not finish. Inspect the encrypted receipt privately.');
const text=(result.stdout||'')+'\n'+(result.stderr||'');
const urls=[...text.matchAll(/https:\/\/[a-z0-9-]+\.netlify\.app/g)].map(x=>x[0]);
const base=urls.find(u=>!u.includes('--'))||urls[0];
if(!base)throw new Error('No live URL returned. Inspect the encrypted receipt.');
const publicInfo={url:base,deployedAt:new Date().toISOString(),claimRequired:true,cli:version,commit:process.env.GITHUB_SHA};
fs.writeFileSync(path.join(out,'public-deploy.json'),JSON.stringify(publicInfo,null,2));
console.log('NETLIFY_PREVIEW_URL='+base);
const checks=[];
function check(name,value){checks.push({name,passed:Boolean(value)});assert.ok(value,name);}
(async()=>{
 const browser=await chromium.launch({executablePath:'/usr/bin/google-chrome',headless:true,args:['--no-sandbox']});
 const context=await browser.newContext({viewport:{width:1440,height:960}});
 const page=await context.newPage(); const exceptions=[];const requests=[];
 page.on('pageerror',e=>exceptions.push(e.message));page.on('request',r=>requests.push(r.url()));
 const response=await page.goto(base+'/?source=investor-deck',{waitUntil:'networkidle',timeout:60000});
 check('HTTPS page loads',response.status()===200);
 check('No-index response header',/noindex/.test(response.headers()['x-robots-tag']||''));
 check('Content security policy is served',Boolean(response.headers()['content-security-policy']));
 check('Existing headline retained',(await page.locator('h1').innerText()).includes('Sharper thinking.'));
 check('Inline form ready',await page.locator('#request-button').isEnabled());
 check('Official logo loads',await page.locator('.logo').evaluate(i=>i.complete&&i.naturalWidth===302));
 await page.evaluate(()=>document.fonts.ready);
 check('Inter typeface loaded',await page.evaluate(()=>document.fonts.check('600 32px Inter')));
 await page.mouse.move(5,5);await page.waitForTimeout(1100);
 await page.screenshot({path:path.join(out,'desktop-live.png'),fullPage:true});
 for(const width of [320,360,390,430,768,1024,1280,1440,1920]){
  await page.setViewportSize({width,height:960});
  check('No horizontal overflow at '+width,await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  check('Form remains available at '+width,await page.locator('#access-form').isVisible());
 }
 await page.setViewportSize({width:390,height:844});await page.screenshot({path:path.join(out,'mobile-live.png'),fullPage:true});
 await page.setViewportSize({width:1440,height:960});
 const deep=await page.goto(base+'/request-access?source=investor-deck',{waitUntil:'networkidle'});
 check('Request access deep link loads',deep.status()===200&&await page.locator('#request-button').isEnabled());
 await page.locator('#request-button').click();
 check('Required email validated',await page.locator('#email-error').isVisible());
 check('Invalid field receives keyboard focus',await page.locator('#email').evaluate(e=>e===document.activeElement));
 await page.locator('#email').fill('not-an-email');await page.locator('#request-button').click();
 check('Invalid email rejected',(await page.locator('#email-error').innerText()).includes('valid email'));
 await page.locator('[data-open-privacy]').first().click();
 check('Privacy notice opens',await page.locator('#privacy-dialog').isVisible());
 check('Existing policy date preserved',(await page.locator('#privacy-copy').innerText()).includes('01/10/2025'));
 await page.keyboard.press('Escape');check('Escape closes policy',!await page.locator('#privacy-dialog').isVisible());
 await page.route('**/rest/v1/early_access',route=>route.fulfill({status:503,contentType:'application/json',body:'{"code":"PRIVATE_SERVICE_FAILURE"}'}));
 await page.locator('#email').fill('offline-check@example.com');await page.locator('#request-button').click();
 await page.locator('#submission-error').waitFor({state:'visible'});
 check('Service failure does not claim success',!await page.locator('#success-content').isVisible());
 check('Form is retryable after failure',await page.locator('#request-button').isEnabled());
 check('Internal service details stay private',!(await page.locator('#submission-error').innerText()).includes('PRIVATE_SERVICE_FAILURE'));
 await page.unroute('**/rest/v1/early_access');
 const testEmail='olumi-preview-v3-'+process.env.GITHUB_RUN_ID+'-'+process.env.GITHUB_RUN_ATTEMPT+'@example.com';
 await page.locator('#email').fill(testEmail);await page.locator('#full-name').fill('Olumi preview verification');
 const wait=page.waitForResponse(r=>r.url().endsWith('/rest/v1/early_access')&&r.request().method()==='POST',{timeout:30000});
 await page.locator('#request-button').click();const saved=await wait;
 check('Real form inserts into existing database',saved.status()===201||saved.status()===204);
 await page.locator('#success-content').waitFor({state:'visible'});
 const payload=saved.request().postDataJSON();
 check('Existing source policy retained',payload.source==='holding_page');
 check('Preview requests distinguishable',payload.utm.experience==='netlify-preview-v3'&&payload.utm.source==='investor-deck');
 check('Success shown only after server confirmation',await page.locator('#success-heading').isVisible());
 await page.mouse.move(5,5);await page.screenshot({path:path.join(out,'success-live.png'),fullPage:true});
 await page.locator('#reset-form').click();
 check('Reset clears contact details',(await page.locator('#email').inputValue())==='');
 await page.locator('#email').fill(testEmail);
 const waitDuplicate=page.waitForResponse(r=>r.url().endsWith('/rest/v1/early_access')&&r.request().method()==='POST');
 await page.keyboard.press('Enter');const duplicate=await waitDuplicate;
 check('Duplicate recognised by existing database',duplicate.status()===409);
 await page.locator('#success-content').waitFor({state:'visible'});
 check('Duplicate has the same non-disclosing confirmation',await page.locator('#success-heading').isVisible());
 await page.goto(base+'/privacy',{waitUntil:'networkidle'});check('Privacy deep link works',await page.locator('#privacy-dialog').isVisible());
 check('No JavaScript exceptions',exceptions.length===0);
 check('No product or AI requests',!requests.some(u=>/etmmuzwxtcjipwphdola|api\.openai\.com|anthropic\.com/.test(u)));
 const absent=await context.request.get(base+'/not-a-real-page');check('Unknown route is a real 404',absent.status()===404);
 const nojs=await browser.newContext({javaScriptEnabled:false});const nj=await nojs.newPage();await nj.goto(base);
 check('No-JavaScript email fallback is visible',await nj.locator('noscript').isVisible());
 await nojs.close();await browser.close();
 const report={...publicInfo,checks,passed:checks.filter(c=>c.passed).length,total:checks.length,testEmail,realInsertStatus:saved.status(),duplicateStatus:duplicate.status(),databaseVerified:false};
 fs.writeFileSync(path.join(out,'verification.json'),JSON.stringify(report,null,2));
 console.log('LIVE_VERIFICATION='+JSON.stringify(report));
})().catch(e=>{fs.writeFileSync(path.join(out,'verification-failure.json'),JSON.stringify({checks,error:e.message},null,2));console.error('VERIFICATION_FAILED='+e.message);process.exit(1)});
